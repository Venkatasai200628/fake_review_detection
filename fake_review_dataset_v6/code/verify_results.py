"""
verify_results.py -- independently re-check the final model's numbers.

  1. REPRODUCE  reload the saved model (out/model/fusion_rf.joblib), rebuild the
                features from scratch, recompute every metric, compare with the
                numbers train_model.py reported
  2. CONFIDENCE 2,000 bootstrap resamples of the test set, grouped by root photo
                -> 95% confidence interval for each metric
  3. LEAKAGE    train the same model on RANDOMLY SHUFFLED labels (5 times).
                If any feature leaked the answer, it would still score well.
                Honest features must fall to ROC-AUC ~0.5.
  4. STABILITY  retrain with 5 different random seeds -> spread of the results

Output: ../out/VERIFY_RESULTS.md

    python verify_results.py
"""
import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (accuracy_score, f1_score, precision_score, recall_score,
                             roc_auc_score, average_precision_score)

import features as F

OUT = '../out'
F.CNN_SCORES_CSV = f'{OUT}/cnn_manip_scores_split.csv'
F.TEXT_SCORES_CSV = f'{OUT}/text_model_scores_split.csv'
lines = ['# Independent verification of the final model', '',
         'Generated by `code/verify_results.py`. Nothing here is copied from earlier logs.', '']


def say(s=''):
    print(s)
    lines.append(s)


def metrics(y, p):
    yh = (p >= 0.5).astype(int)
    return {'accuracy': accuracy_score(y, yh), 'f1': f1_score(y, yh),
            'precision': precision_score(y, yh, zero_division=0), 'recall': recall_score(y, yh),
            'roc_auc': roc_auc_score(y, p), 'pr_auc': average_precision_score(y, p)}


full = pd.read_csv(f'{OUT}/reviews_full.csv')
X = pd.concat(F.build_all(full).values(), axis=1).replace([np.inf, -np.inf], np.nan).fillna(0.0)
X.index = full.review_id.values
tr = pd.read_csv(f'{OUT}/train.csv')
te = pd.read_csv(f'{OUT}/test_balanced.csv')
ho = pd.read_csv(f'{OUT}/holdout_realistic.csv')
model = joblib.load(f'{OUT}/model/fusion_rf.joblib')
import json
cols = json.load(open(f'{OUT}/model/model_meta.json'))['features']

# ---------------------------------------------------------------- 1 reproduce
say('## 1. Reproduce the saved model\'s numbers')
say('')
reported = pd.read_csv(f'{OUT}/model/final_model_results.csv')
say('| Test set | Metric | Reported | Recomputed now | Match |')
say('|---|---|---|---|---|')
for (name, part), rep in zip([('test_balanced', te), ('holdout_realistic', ho)], reported.to_dict('records')):
    m = metrics(part.is_fake.values, model.predict_proba(X.loc[part.review_id, cols].values)[:, 1])
    for k, rk in [('pr_auc', 'PR-AUC'), ('roc_auc', 'ROC-AUC'), ('f1', 'F1'), ('precision', 'Precision'), ('recall', 'Recall')]:
        r = rep[rk]
        say(f"| {name} | {rk} | {r:.3f} | {m[k]:.3f} | {'yes' if abs(r - m[k]) < 0.0015 else 'NO'} |")
say('')

# ------------------------------------------------------------- 2 confidence
say('## 2. 95% confidence intervals (2,000 bootstrap resamples, grouped by root photo)')
say('')
rng = np.random.default_rng(0)
say('| Test set | Metric | Value | 95% CI |')
say('|---|---|---|---|')
for name, part in [('test_balanced (50% fake)', te), ('holdout_realistic (15% fake)', ho)]:
    y = part.is_fake.values
    p = model.predict_proba(X.loc[part.review_id, cols].values)[:, 1]
    base = metrics(y, p)
    roots = part.root_image_id.values
    uniq = np.unique(roots)
    idx_of = {r: np.where(roots == r)[0] for r in uniq}
    boot = {k: [] for k in base}
    for _ in range(2000):
        pick = np.concatenate([idx_of[r] for r in rng.choice(uniq, len(uniq))])
        if y[pick].min() == y[pick].max():
            continue
        for k, v in metrics(y[pick], p[pick]).items():
            boot[k].append(v)
    for k in ['accuracy', 'f1', 'roc_auc', 'pr_auc']:
        lo, hi = np.percentile(boot[k], [2.5, 97.5])
        say(f"| {name} | {k} | {base[k]:.3f} | {lo:.3f} – {hi:.3f} |")
say('')

# ---------------------------------------------------------------- 3 leakage
say('## 3. Label-shuffle test (does any feature leak the answer?)')
say('')
say('The same Random Forest is trained on the same features, but with the training labels **randomly shuffled**.')
say('Honest features cannot predict shuffled labels, so the test ROC-AUC must be ~0.5.')
say('')
aucs = []
for s in range(5):
    ysh = np.random.default_rng(100 + s).permutation(tr.is_fake.values)
    m = RandomForestClassifier(500, min_samples_leaf=2, class_weight='balanced', n_jobs=-1, random_state=s)
    m.fit(X.loc[tr.review_id, cols].values, ysh)
    aucs.append(roc_auc_score(te.is_fake.values, m.predict_proba(X.loc[te.review_id, cols].values)[:, 1]))
say(f"Shuffled-label ROC-AUC over 5 runs: {', '.join(f'{a:.3f}' for a in aucs)} "
    f"(mean {np.mean(aucs):.3f}) -> {'PASS: no leakage' if abs(np.mean(aucs) - 0.5) < 0.05 else 'FAIL: something leaks'}")
say('')

# -------------------------------------------------------------- 4 stability
say('## 4. Stability across random seeds (retrained 5 times)')
say('')
res = []
for s in range(5):
    m = RandomForestClassifier(500, min_samples_leaf=2, class_weight='balanced', n_jobs=-1, random_state=1000 + s)
    m.fit(X.loc[tr.review_id, cols].values, tr.is_fake.values)
    a = metrics(te.is_fake.values, m.predict_proba(X.loc[te.review_id, cols].values)[:, 1])
    b = metrics(ho.is_fake.values, m.predict_proba(X.loc[ho.review_id, cols].values)[:, 1])
    res.append({'seed': 1000 + s, 'test accuracy': a['accuracy'], 'test F1': a['f1'],
                'test ROC-AUC': a['roc_auc'], 'holdout PR-AUC': b['pr_auc']})
r = pd.DataFrame(res)
say('| Metric | Mean | Min | Max |')
say('|---|---|---|---|')
for c in ['test accuracy', 'test F1', 'test ROC-AUC', 'holdout PR-AUC']:
    say(f"| {c} | {r[c].mean():.3f} | {r[c].min():.3f} | {r[c].max():.3f} |")

open(f'{OUT}/VERIFY_RESULTS.md', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('\nsaved ../out/VERIFY_RESULTS.md')
